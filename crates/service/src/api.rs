#[cfg(test)]
mod tests {
    use axum::http::StatusCode;
    use axum::http::header::AUTHORIZATION;
    use axum::response::IntoResponse;

    use super::*;

    #[utoipa::path(
        get,
        path = "/_test/protected",
        tag = "system",
        operation_id = "testProtected",
        summary = "Test-only protected composition seam",
        security(("bearerAuth" = [])),
        extensions(("x-security-decision" = json!({
            "exposure": "protected",
            "rationale": "test-only route proving the production bearer composition seam"
        }))),
        responses(
            (status = 200, description = "verified", content_type = "text/plain", body = String),
            infra_http::authn::ProtectedOperationProblemResponses,
        )
    )]
    async fn protected(
        principal: infra_http::VerifiedPrincipal,
        headers: axum::http::HeaderMap,
    ) -> impl IntoResponse {
        let authorization_was_removed = !headers.contains_key(AUTHORIZATION);
        let identity_was_verified = !principal.issuer().is_empty()
            && (principal.subject().is_some() || principal.client_id().is_some());
        if authorization_was_removed && identity_was_verified {
            (StatusCode::OK, "verified").into_response()
        } else {
            StatusCode::INTERNAL_SERVER_ERROR.into_response()
        }
    }

    fn public_check(
        document: Document,
    ) -> Result<infra_http::Application, infra_http::FinalizeError> {
        HttpContract::new(OpenApiRouter::with_openapi(document)).build(
            (),
            infra_http::Authentication::Public,
            &infra_http::HardenOptions {
                max_body_bytes: 1024,
                request_timeout: std::time::Duration::from_secs(1),
                max_in_flight: None,
                admission_wait: std::time::Duration::ZERO,
                log_health_probes: false,
                draining: None,
            },
        )
    }

    #[test]
    fn protected_contract_refuses_public_finalization_without_a_composer() {
        let document = assemble()
            .routes(utoipa_axum::routes!(protected))
            .into_openapi();
        assert!(matches!(
            public_check(document),
            Err(infra_http::FinalizeError::ProtectedOperation { .. })
        ));
    }

    #[test]
    fn public_probe_contract_does_not_depend_on_a_verifier() {
        let document = HttpContract::new(assemble())
            .with_probes("/")
            .into_openapi();
        assert!(public_check(document).is_ok());
    }
}
